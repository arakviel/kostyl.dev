// Усі арифметичні оператори для int і double.
int a = 17, b = 5;
Console.WriteLine($"a + b = {a + b}");
Console.WriteLine($"a - b = {a - b}");
Console.WriteLine($"a * b = {a * b}");
Console.WriteLine($"a / b = {a / b}");
Console.WriteLine($"a % b = {a % b}");
Console.WriteLine($"-a = {-a}, +a = {+a}");
Console.WriteLine();

double x = 17, y = 5;
Console.WriteLine($"x / y = {x / y}");
Console.WriteLine($"x % y = {x % y}");
Console.WriteLine();

int i = 5;
i++;
Console.WriteLine($"після i++: i = {i}");
i--;
i--;
Console.WriteLine($"після двох i--: i = {i}");
